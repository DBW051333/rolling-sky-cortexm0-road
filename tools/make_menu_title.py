"""Generate a fixed English logo and a golden i dot as small code tables."""
from pathlib import Path
from math import sqrt
from PIL import Image, ImageDraw, ImageFont
width,height=196,84
font=ImageFont.truetype('C:/Windows/Fonts/segoeuiz.ttf',36)
small=ImageFont.truetype('C:/Windows/Fonts/segoeuiz.ttf',27)
letters=Image.new('1',(width,height));draw=ImageDraw.Draw(letters)
origin=(32,-3)
draw.text(origin,'Rolling',font=font,fill=1)
ix=origin[0]+round(font.getlength('Roll'))
glyph=Image.new('1',(24,52));ImageDraw.Draw(glyph).text((0,0),'i',font=font,fill=1)
occupied=[y for y in range(52) if any(glyph.getpixel((x,y)) for x in range(24))]
dot_rows=[]
for y in occupied:
    if dot_rows and y>dot_rows[-1]+1:break
    dot_rows.append(y)
xs=[x for y in dot_rows for x in range(24) if glyph.getpixel((x,y))]
center_x=ix+(min(xs)+max(xs))//2
center_y=origin[1]+(dot_rows[0]+dot_rows[-1])//2
draw.rectangle((ix,origin[1]+dot_rows[0],ix+max(xs)+1,origin[1]+dot_rows[-1]),fill=0)
size=12;ball_x=center_x-size//2;ball_y=center_y-size//2
sky=Image.new('1',(width,height));d=ImageDraw.Draw(sky)
label='S K Y';label_w=round(small.getlength(label))
d.text(((width-label_w)//2,43),label,font=small,fill=1)
canvas=Image.new('L',(width,height))
for mask,color in ((letters,2),(sky,3)):
    for y in range(height):
        for x in range(width):
            if mask.getpixel((x,y)) and x+2<width and y+3<height:canvas.putpixel((x+2,y+3),1)
for mask,color in ((letters,2),(sky,3)):
    for y in range(height):
        for x in range(width):
            if mask.getpixel((x,y)):canvas.putpixel((x,y),color)

def rle(row,bits,limit):
    out=[];previous=row[0];count=0
    for value in row:
        if value!=previous or count==limit:
            out.append((count<<bits)|previous);previous=value;count=0
        count+=1
    out.append((count<<bits)|previous)
    return out
runs=[]
for y in range(height):runs.extend(rle([canvas.getpixel((x,y)) for x in range(width)],2,63))
ball=[]
for y in range(size):
    row=[]
    for x in range(size):
        nx,ny=(x+.5-size/2)/(size/2),(y+.5-size/2)/(size/2)
        radius=nx*nx+ny*ny;value=0
        if radius<=1:
            nz=sqrt(1-radius)
            light=max(0,-.42*nx-.6*ny+.68*nz)
            value=min(6,1+int(light*5.7))
            if nx<-.2 and ny<-.35 and nz>.6:value=7
        row.append(value)
    ball.extend(rle(row,3,31))
out=['/* Generated by tools/make_menu_title.py; fixed italic English logo. */',
'#ifndef MENU_TITLE_H','#define MENU_TITLE_H',f'#define TITLE_WIDTH {width}',f'#define TITLE_HEIGHT {height}',f'#define TITLE_BALL_X {ball_x}',f'#define TITLE_BALL_Y {ball_y}',f'#define TITLE_BALL_SIZE {size}']
def array(kind,name,values):
    out.append(f'static const {kind} {name}[]={{')
    for i in range(0,len(values),20):out.append('    '+','.join(str(v) for v in values[i:i+20])+',')
    out.append('};')
array('uint16_t','title_palette',[0x347f,0x2357,0xffff,0xb7ff])
array('uint8_t','title_runs',runs)
array('uint16_t','title_ball_palette',[0,0x6980,0xa281,0xd3c1,0xf521,0xfe23,0xff29,0xffda])
array('uint8_t','title_ball_runs',ball)
out.extend(['#endif',''])
(Path(__file__).resolve().parents[1]/'firmware/menu_title.h').write_text('\n'.join(out),encoding='ascii')
print(f'Fixed logo {width}x{height}, {len(runs)} RLE bytes; golden ball {len(ball)} bytes, at {ball_x},{ball_y}')
