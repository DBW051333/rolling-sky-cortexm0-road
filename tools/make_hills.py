"""Author a 288-row Hills route with mandatory gates and staggered jumps.
The route is built first; inexpensive height-based elements are layered on it.
"""
import json
from pathlib import Path
base=Path(__file__).resolve().parents[1]
n=288;ground=[31]*n;tiles=[];lanes=[3]*n;air=set();gates=[]
def path(a,b,lane,mask=None):
 for r in range(a,b):ground[r]=(1<<(lane-1)) if mask is None else mask;lanes[r]=lane
def void(a,b,target):
 path(a,b,target,0);air.update(range(a,b))
def event(row,lane,kind):tiles.append([row,1<<(lane-1),kind])
def gate(row,lane,action='ground'):gates.append([row,lane,action])
def chain(nodes,exit_end):
 for i,(row,lane) in enumerate(nodes):
  path(row,row+1,lane);gate(row,lane,'jump' if i+1<len(nodes) else 'ground')
  if i+1<len(nodes):
   event(row,lane,1);next_row,next_lane=nodes[i+1];void(row+1,next_row,next_lane)
   # The pad flight spans four rows from pad contact, so the landing row is
   # pad+4: keep a full-width strip there or every hop dies one row short.
   ground[row+4]=31
 path(nodes[-1][0],exit_end,nodes[-1][1])
# 1. Ground route: single-column gates, with roomy transition strips.
path(8,12,2)
for a,lane in ((12,2),(20,3),(28,4),(36,3),(44,2)):
 path(a,a+4,lane);gate(a,lane)
for a,lane,mask in ((16,3,6),(24,4,12),(32,3,12),(40,2,6)):path(a,a+4,lane,mask)
event(8,2,3);event(20,3,3);event(28,4,3);event(44,2,3)
# 2. First mandatory gap, then the first staggered chain.
path(48,53,2);chain([(52,2),(57,3)],64)
path(64,69,3);chain([(68,3),(73,4),(78,2),(83,3)],88)
path(88,92,2,6);path(92,96,2);gate(92,2)
# 3. Base corridor for the new short-jump and full-depth ground blocker.
path(96,108,2);path(108,112,3,6);path(112,120,3)
path(120,124,2,6);path(124,128,2);gate(124,2)
# 4. Ground-only route through overhead hazards and a second short leap.
path(128,136,2);path(136,138,2);path(138,144,3)
path(144,148,4,12);path(148,152,4);path(152,156,3,12);path(156,160,3)
gate(132,2);gate(150,4);gate(156,3)
# 5. Low wall, gap, shifted landing, another forced flight.
path(160,165,3);chain([(164,3),(169,2)],174)
# Give the low barrier its own supported row, with the following rows empty.
path(166,167,3);event(166,3,2);air.add(166)
path(174,175,2);chain([(174,2),(179,4)],184)
path(184,188,3,12);path(188,192,3);gate(188,3)
# 6. Mandatory ground weave and independent glass animations.
for a,b,lane,mask in ((192,196,3,None),(196,200,2,6),(200,204,2,None),(204,208,3,6),(208,212,3,None),(212,216,4,12),(216,220,4,None),(220,224,3,12)):
 path(a,b,lane,mask)
for r,c in ((192,3),(200,2),(208,3),(216,4)):event(r,c,3);gate(r,c)
# 7/8. Two three-jump finales, separated by a grounded transition.
path(224,229,3);chain([(228,3),(233,1),(238,4),(243,2)],248)
path(248,252,3,6);path(252,256,3);gate(252,3)
path(256,261,3);chain([(260,3),(265,5),(270,2),(275,3)],288)
# Height-based rules, independent from all palette/model choices.
event(100,2,6);void(101,102,2);path(102,108,2);air.add(102);event(102,2,5);gate(100,2,'short')
event(114,3,1);event(116,3,7);air.update(range(115,119));gate(114,3,'jump')
# Overhead beams cover all lanes, so the tempting normal jumps are not bypasses.
path(128,132,2,6);event(130,3,1)
for r,center,posts in ((132,2,5),(150,4,20)):
 ground[r]=(1<<(center-1))|posts;tiles.append([r,posts,4]);tiles.append([r,31,5])
path(148,150,4,12);event(148,3,1)
event(136,2,6);void(137,138,3);path(138,144,3);air.add(138);event(138,3,5);gate(136,2,'short');gate(138,3)
# Connected ground gates: an adjacent blocked tile closes a plausible lane.
# No isolated decorative islands; collision type remains independent of art.
for row,blocked_lane in ((12,3),(28,3),(44,3),(92,3),(188,4),(208,2),(252,2)):
 ground[row]|=1<<(blocked_lane-1);event(row,blocked_lane,4)
# Collectibles ride the authored route lanes only, so they never open a new
# path through the forced gates; they reward following the designed line.
gem_defs=[(10,2),(18,3),(26,4),(34,3),(42,2),(62,3),(90,2),(124,2),(186,3),(222,3),(250,3),(282,3)]
# Encode the same design for the editable SD pack and ROM fallback.
tiles.sort(key=lambda t:(t[0],t[2]))
ground_runs=[];i=0
while i<n:
 end=i+1
 while end<n and ground[end]==ground[i]:end+=1
 if ground[i]!=31:ground_runs.append([i,end-i,ground[i]])
 i=end
route=[];i=0
while i<n:
 lane=lanes[i];mode='air' if i in air else 'ground';end=i+1
 while end<n and lanes[end]==lane and ('air' if end in air else 'ground')==mode:end+=1
 route.append([i,end-i,lane,mode]);i=end
gates.sort()
level={'name':'Hills','id':4,'rows':n,'ground':ground_runs,'tiles':tiles,'route':route,'gates':gates,'gems':[[r,l] for r,l in gem_defs]}
p=base/'levels/levels.json';obj=json.loads(p.read_text(encoding='utf-8'))
obj['levels']=[l for l in obj['levels'] if l.get('id')!=4]+[level]
p.write_text(json.dumps(obj,indent=2)+'\n',encoding='utf-8')
lines=['/* Generated by tools/make_hills.py: mandatory gates and staggered flights. */','static const GroundRun hills_ground[]={']
lines.extend('    {'+','.join(map(str,g))+'},' for g in ground_runs);lines.append('};')
lines.append('static const TileEvent hills_tiles[]={')
lines.extend('    {'+','.join(map(str,t))+'},' for t in tiles);lines.append('};')
lines.append('static const LevelGem hills_gems[]={')
lines.extend('    {%d,%d},'%(r,l-1) for r,l in gem_defs);lines.append('};')
lines.append(f'static const Level hills_level={{hills_ground,hills_tiles,{n},{len(ground_runs)},{len(tiles)},4,hills_gems,0,{len(gem_defs)},0}};')
(base/'firmware/hills_level.h').write_text('\n'.join(lines)+'\n',encoding='ascii')
print(f'Hills: {n} rows, {len(tiles)} events, {len(gates)} mandatory design gates; {len(ground_runs)} ground runs; {len(gem_defs)} gems.')
