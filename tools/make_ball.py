"""Build a tiny RGB565 RLE sprite, not an image or preview.

Lighting is calculated offline; M0 only copies short color runs.
"""
from math import sqrt
from pathlib import Path

LEFT, TOP, WIDTH, HEIGHT = 86, 158, 68, 68
CX, CY, R = 120, 192, 34
palette = [(111,50,7),(162,81,8),(210,121,9),(245,164,14),
           (255,197,25),(255,225,75),(255,250,208)]

def rgb565(rgb):
    r,g,b=rgb
    return ((r>>3)<<11)|((g>>2)<<5)|(b>>3)

light=(-0.42,-0.60,0.68)
norm=sqrt(sum(v*v for v in light))
light=tuple(v/norm for v in light)
half=(light[0],light[1],light[2]+1)
norm=sqrt(sum(v*v for v in half))
half=tuple(v/norm for v in half)

def pixel(x,y):
    color=0 # Transparent outside the sphere: no ground shadow.
    nx,ny=(x+0.5-CX)/R,(y+0.5-CY)/R
    d=nx*nx+ny*ny
    if d<=1:
        nz=sqrt(max(0,1-d))
        diffuse=max(0,nx*light[0]+ny*light[1]+nz*light[2])
        specular=max(0,nx*half[0]+ny*half[1]+nz*half[2])**24
        index=min(5,int(diffuse*5.9))
        if specular>0.38: index=6
        if nz<0.18: index=0
        color=index+1
    return color

runs=[]
offsets=[0]
for y in range(TOP,TOP+HEIGHT):
    row=[pixel(x,y) for x in range(LEFT,LEFT+WIDTH)]
    count=1
    for i in range(1,len(row)+1):
        if i<len(row) and row[i]==row[i-1]: count+=1
        else:
            while count>31:
                runs.append((31<<3)|row[i-1])
                count-=31
            runs.append((count<<3)|row[i-1])
            count=1
    offsets.append(len(runs))

out=['/* Generated by tools/make_ball.py. Transparent runs use color 0. */',
     '#ifndef BALL_SPRITE_H','#define BALL_SPRITE_H',
     f'#define BALL_LEFT {LEFT}',f'#define BALL_TOP {TOP}',f'#define BALL_WIDTH {WIDTH}',f'#define BALL_HEIGHT {HEIGHT}',
     'static const uint16_t ball_palette[]={0,'+','.join('0x%04x'%rgb565(c) for c in palette)+'};',
     'static const uint16_t ball_row_offset[]={'+','.join(map(str,offsets))+'};',
     'static const uint8_t ball_runs[]={']
for i in range(0,len(runs),6):
    out.append('    '+','.join('0x%02xu'%v for v in runs[i:i+6])+',')
out+=['};','#endif','']
target=Path(__file__).resolve().parents[1]/'firmware'/'ball_sprite.h'
target.write_text('\n'.join(out),encoding='ascii')
colors=[0]+[rgb565(c) for c in palette]
print(f'Ball sprite: diameter={WIDTH}, {len(runs)} runs, {len(runs)+len(offsets)*2+len(colors)*2} bytes read-only; center={colors[pixel(120,192)]:04x}, highlight={colors[pixel(109,179)]:04x}, lower={colors[pixel(135,207)]:04x}; no ground shadow')
