"""Generate compact RGB565 palettes for procedural sphere skins.

Patterns live in firmware/player.c and reuse the original sphere silhouette.
Run from any directory to regenerate firmware/player_skins.h.
"""
from pathlib import Path

SKINS = [
    ("ION CYAN", "003044 005678 008da8 12c5df 5cefff", "ff28d9", "eaffff"),
    ("VOID ORB", "19052e 35085b 5b168f 8633c8 b86cff", "18c5dc", "88ffff"),
    ("PINK NOVA", "470c3c 78185e ae2586 dc50b4 ff9bd8", "df58fc", "fff0ff"),
    ("PLASMA BOLT", "092056 123c88 2363b5 388de2 70bbff", "c8b01c", "ffff96"),
    ("GLACIER", "123749 235b73 40849e 77b2c9 bbe8f5", "22a2f5", "f0ffff"),
    ("TOXIC GRID", "123609 28580e 46821c 77b02d bbef57", "2ae673", "d8ff98"),
    ("SOLAR FLARE", "581000 8a2004 bc4008 e86c18 ffa54a", "ff4168", "ffffac"),
    ("MAGNETAR", "290944 4c0f70 7d21a6 aa46d0 dc87f7", "f545c3", "b0ffff"),
    ("CHROME X", "182330 364553 5c7080 92a7b5 d9e8ec", "39acda", "f0ffff"),
    ("QUANTUM", "05382f 0b5c4c 16896e 31b78b 83e6b9", "a948f8", "f3c5ff"),
    ("INFERNO", "260b13 4a1018 791e1d ac3924 e46a39", "e63a09", "ffea78"),
]

def rgb565(value):
    r, g, b = bytes.fromhex(value)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def main():
    names = ["GOLD CORE"] + [skin[0] for skin in SKINS]
    assert len(names) == 12 and all(len(name) < 12 for name in names)
    lines = ["/* Generated by tools/make_players.py; procedural sphere palettes. */",
             "static const char skin_names[PLAYER_COUNT][12]={"]
    lines.extend(f' "{name}",' for name in names)
    lines += ["};", "static const uint16_t skin_palettes[PLAYER_COUNT-1][8]={"]
    for _, shades, accent, highlight in SKINS:
        colors = [0] + [rgb565(v) for v in shades.split() + [accent, highlight]]
        assert len(colors) == 8
        lines.append(" {" + ",".join(f"0x{v:04x}" for v in colors) + "},")
    lines.append("};\n")
    target = Path(__file__).resolve().parents[1] / "firmware/player_skins.h"
    target.write_bytes("\n".join(lines).encode("utf-8"))

if __name__ == "__main__":
    main()
