"""Bake only a title silhouette; the firmware lights and extrudes it at runtime.

Uses a locally installed bold font. The checked-in header makes normal builds
independent of fonts and Pillow. Pass an optional font path to regenerate.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = Path(sys.argv[1] if len(sys.argv) > 1 else 'C:/Windows/Fonts/arialbd.ttf')
SCALE = 4
font = ImageFont.truetype(str(FONT), 32 * SCALE)
box = font.getbbox('Rolling Sky')
source = Image.new('L', (box[2] - box[0] + 4, box[3] - box[1] + 4))
ImageDraw.Draw(source).text((-box[0] + 2, -box[1] + 2), 'Rolling Sky', font=font, fill=255)
mask = source.resize((174, 30), Image.Resampling.LANCZOS)
data = []
for y in range(30):
    for byte in range(22):
        value = 0
        for bit in range(8):
            x = byte * 8 + bit
            if x < 174 and mask.getpixel((x, y)) >= 110:
                value |= 1 << bit
        data.append(value)
lines = ['/* Generated by tools/make_menu_title.py: 174 x 30, 1 bit/pixel. */',
         'static const uint8_t title_mask[660]={']
lines += [' ' + ','.join(str(v) for v in data[i:i+22]) + ',' for i in range(0, len(data), 22)]
lines.append('};\n')
(ROOT / 'firmware/menu_title.h').write_bytes('\n'.join(lines).encode('utf-8'))
