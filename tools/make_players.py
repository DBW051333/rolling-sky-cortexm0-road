def main():
    lines = ["/* Generated by tools/make_players.py; original pixel art. */",
             "static const uint8_t chibi_runs[4][154]={"]
    offsets = []
    for sprite in ART:
        assert len(sprite) == 17 and all(len(row) == 17 for row in sprite)
        data, offset = [], [0]
        for row in sprite:
            color, length = 0, 0
            for c in row:
                value = 0 if c == '.' else int(c)
                if length and (value != color or length + 4 > 31):
                    data.append((length << 3) | color)
                    length = 0
                color, length = value, length + 4
            data.append((length << 3) | color)
            offset.append(len(data))
        assert len(data) <= 154
        offsets.append(offset)
        lines.append(" {" + ",".join(str(v) for v in data) + "},")
    lines += ["};", "static const uint8_t chibi_offsets[4][18]={"]
    for offset in offsets:
        lines.append(" {" + ",".join(str(v) for v in offset) + "},")
    lines.append("};\n")
    target = Path(__file__).resolve().parents[1] / 'firmware/player_pixels.h'
    target.write_text('\n'.join(lines), encoding='utf-8')

if __name__ == '__main__':
    main()
